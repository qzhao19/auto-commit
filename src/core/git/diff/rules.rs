/// Header substrings (already lowercase).
const GENERATED_HEADER_MARKERS: &[&str] = &[
    "@generated",
    "code generated by",
    "automatically generated",
    "this file was generated",
    "this file is generated",
    "do not edit",
    "do not modify",
    "auto-generated",
    "autogenerated",
    "generated by the protocol buffer compiler",
    "generated by protoc",
];

const COMMENT_PREFIXES: &[&str] = &["//", "/*", "*", "#", "--", ";"];

/// Basename against lockfile registry
pub fn match_lock_file(path: &Path) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };

    LOCK_FILES
        .iter()
        .any(|lock| name.eq_ignore_ascii_case(lock))
}

pub fn match_generated_path(path: &Path) -> bool {
    let Some(parent) = path.parent() else {
        return false;
    };

    parent.components().any(|component| match component {
        Component::Normal(segment) => segment
            .to_str()
            .map(|name| {
                GENERATED_DIR_NAMES
                    .iter()
                    .any(|dir| name.eq_ignore_ascii_case(dir))
            })
            .unwrap_or(false),
        _ => false,
    })
}

/// Basename suffix match against known codegen output patterns
pub fn match_generated_name(path: &Path) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };
    let lower = name.to_ascii_lowercase();
    GENERATED_NAME_SUFFIXES.iter().any(|s| lower.ends_with(s))
}

/// Marker scan over the blob head (first ~512 bytes).
pub fn match_generated_header(header: &[u8]) -> bool {
    let lower = String::from_utf8_lossy(header).to_ascii_lowercase();

    if GENERATED_HEADER_MARKERS.iter().any(|m| lower.contains(m)) {
        return true;
    }

    lower.lines().any(is_generated_by_comment_line)
}

fn is_generated_by_comment_line(line: &str) -> bool {
    let trimmed = line.trim_start();
    let Some(rest) = COMMENT_PREFIXES
        .iter()
        .find_map(|prefix| trimmed.strip_prefix(prefix))
    else {
        return false;
    };
    rest.trim_start().starts_with("generated by")
}

/// Phase A: Lock → Generated(path/name).
pub fn classify_by_name(path: &Path) -> Option<FileCategory> {
    if match_lock_file(path) {
        return Some(FileCategory::DependencyLock);
    }
    if match_generated_path(path) || match_generated_name(path) {
        return Some(FileCategory::Generated);
    }
    None
}

/// Phase B residue: Generated or None (→ SemanticText).
pub fn classify_by_header(header: &[u8]) -> Option<FileCategory> {
    if match_generated_header(header) {
        Some(FileCategory::Generated)
    } else {
        None
    }
}
